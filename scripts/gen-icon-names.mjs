// Regenerates src/ui/icon-names.ts from the installed vue-iconsax (it ships no types).
// Run after upgrading vue-iconsax: node scripts/gen-icon-names.mjs
import { readdirSync, writeFileSync } from 'node:fs'

const dir = new URL('../node_modules/vue-iconsax/dist/components/icons/', import.meta.url)
const names = readdirSync(dir)
  .filter((f) => f.endsWith('.vue.js'))
  .map((f) => f.slice(0, -'.vue.js'.length))
  .sort()

writeFileSync(
  new URL('../src/ui/icon-names.ts', import.meta.url),
  `// Generated by scripts/gen-icon-names.mjs from vue-iconsax. Do not edit.\nexport type IconName =\n${names.map((n) => `  | '${n}'`).join('\n')}\n`,
)
console.log(`${names.length} icon names`)
